// Generate tokens.json and tokens.ts from the :root block of css/tokens.css.
// Used by build.mjs (writes the files) and check.mjs (verifies the committed
// copies match a fresh generation). Pure: css text + version in, strings out.

const SECTION_RE = /^(──|Tier\s)/;

/** Parse the first top-level `:root { … }` block into an ordered token list. */
export function parseRootTokens(css) {
	const m = css.match(/^:root\s*\{\n([\s\S]*?)^\}/m);
	if (!m) throw new Error("css/tokens.css: no :root block found");
	const body = m[1];
	const out = new Map();
	let section = "";
	const re = /\/\*([\s\S]*?)\*\/|(--[a-z0-9-]+)\s*:\s*([^;]+);/g;
	for (const t of body.matchAll(re)) {
		if (t[1] !== undefined) {
			const text = t[1].trim();
			if (!SECTION_RE.test(text)) continue;
			// "── Motion (DS-014) — movement durations …" → "Motion (DS-014)"
			section = text.replace(/^[─\s]+|[─\s]+$/g, "").replace(/\s+/g, " ").split(" — ")[0].trim();
			continue;
		}
		const name = t[2].slice(2);
		if (out.has(name)) throw new Error(`css/tokens.css: duplicate token --${name} in :root`);
		out.set(name, { value: t[3].trim(), section });
	}
	return out;
}

/** Resolve every var(--x) reference to a literal, following chains. */
export function resolveAll(tokens) {
	const cache = new Map();
	const resolve = (name, stack = []) => {
		if (cache.has(name)) return cache.get(name);
		const tok = tokens.get(name);
		if (!tok) throw new Error(`css/tokens.css: --${stack.at(-1) ?? "?"} references undefined --${name}`);
		if (stack.includes(name)) throw new Error(`css/tokens.css: circular reference via --${name}`);
		const resolved = tok.value.replace(/var\((--[a-z0-9-]+)\)/g, (_, ref) => resolve(ref.slice(2), [...stack, name]));
		cache.set(name, resolved);
		return resolved;
	};
	for (const name of tokens.keys()) resolve(name);
	return cache;
}

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

/** @returns {{ json: string, ts: string, count: number }} */
export function generateTokens(css, version) {
	const parsed = parseRootTokens(css);
	const resolved = resolveAll(parsed);

	const json = {
		name: "@saga-ed/product-style",
		version,
		source: "css/tokens.css",
		tokens: Object.fromEntries(
			[...parsed].map(([name, { value, section }]) => [name, { value, resolved: resolved.get(name), section }])
		),
	};

	const q = (s) => JSON.stringify(s);
	const tokensLines = [...parsed.keys()].map((n) => `\t${q(n)}: ${q(resolved.get(n))},`);
	const sagaLines = [...parsed.keys()]
		.filter((n) => n.startsWith("saga-"))
		.map((n) => `\t${camel(n.slice("saga-".length))}: ${q(resolved.get(n))},`);
	const chart = [];
	for (let i = 1; parsed.has(`chart-${i}`); i++) chart.push(resolved.get(`chart-${i}`));
	const ts = [
		"// Generated by scripts/build.mjs from css/tokens.css. Do not edit; run `npm run build`.",
		"// Every value is the resolved literal, for canvas and JS code that cannot read CSS.",
		"",
		"/** Every :root token by name (without the leading --), resolved. */",
		"export const tokens = {",
		...tokensLines,
		"} as const;",
		"",
		"/** Tier 1 brand primitives (--saga-*), kebab → camelCase. */",
		"export const saga = {",
		...sagaLines,
		"} as const;",
		"",
		"/** Categorical chart series, --chart-1..8 in order. */",
		`export const chart = [${chart.map(q).join(", ")}] as const;`,
		"",
	].join("\n");

	return { json: JSON.stringify(json, null, "\t") + "\n", ts, count: parsed.size };
}
